import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { NotificationStore } from '../dist/notification-store.js';
import { ImportArchive, importKinds } from '../dist/import-archive.js';
const directory = await mkdtemp(join(tmpdir(), 'eduvo-local-checks-'));
const notificationPath = join(directory, 'notifications.json');
const store = new NotificationStore(notificationPath);
const phoneA = '+60111111111', phoneB = '+60222222222';
const target = await store.send(phoneA, 'Member message', 'Welcome back.', 'admin');
assert.equal((await store.list(phoneA)).length, 1);
assert.equal((await store.list(phoneB)).length, 0);
assert.equal((await store.list(phoneA))[0].IsUnread, true);
await assert.rejects(store.detail(phoneB, target.NotificationId), /not found/i);
await assert.rejects(store.read(phoneB, target.NotificationId), /not found/i);
await store.read(phoneA, target.NotificationId);
assert.equal((await store.list(phoneA))[0].IsUnread, false);
await store.send(null, 'Announcement', 'A shared update.', 'admin');
await store.read(phoneA);
assert.equal((await store.list(phoneA)).every(row => !row.IsUnread), true);
assert.equal((await store.list(phoneB))[0].IsUnread, true);
assert.equal((await new NotificationStore(notificationPath).list(phoneA)).length, 2);
await Promise.all(Array.from({length: 10}, (_, index) => store.send(phoneA, `Message ${index}`, 'Saved concurrently.', 'merchant')));
assert.equal((await store.list(phoneA)).length, 12);
await assert.rejects(store.send('', 'Title', 'Body', 'admin'), /valid recipient/i);
await assert.rejects(store.send(phoneA, '', 'Body', 'admin'), /title/i);
const archivePath = join(directory, 'imports.json');
const archive = new ImportArchive(archivePath);
for (const kind of importKinds) await archive.save(kind, {Id:'synthetic-row', Password:'not-a-real-credential', Value:12});
assert.equal((await archive.list()).length, 13);
assert.equal((await archive.list('wallets')).length, 1);
assert.equal((await archive.save('wallets', {Value:12, Password:'different', Id:'synthetic-row'})).duplicate, true);
assert.equal((await archive.list()).length, 13);
assert.equal((await readFile(archivePath, 'utf8')).includes('Password'), false);
assert.equal((await new ImportArchive(archivePath).list()).length, 13);
assert.throws(() => archive.save('unknown', {}), /valid import/i);
await writeFile(join(directory, 'corrupt.json'), 'broken');
await assert.rejects(new NotificationStore(join(directory,'corrupt.json')).list(phoneA));
console.log('20 local substitute checks passed. Temporary synthetic data only; no provider API calls.');
